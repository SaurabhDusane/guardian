"""Guardian benchmarks on the demo pipeline, at several scales.

    uv sync --extra observability                  # for configuration (d) below
    uv run python bench/run_bench.py               # 10k, 100k and 1M rows, 5 repeats
    uv run python bench/run_bench.py --scales 10000 100000
    uv run python bench/run_bench.py --quick       # 10k rows, 2 repeats: a sanity check
    uv run python bench/update_readme.py           # README Results table <- results.json

Measurements, each at every scale (rows generated by the source block):

1. Overhead breakdown: one pipeline run of the same blocks, on clean data,
   (a) bare: the block functions in topological order, no Guardian;
   (b) Guardian core only: validation, snapshots, quarantine, events at sample rate 0.1,
       with provenance recording switched off (a no-op provenance store);
   (c) (b) + provenance;
   (d) (c) + observability exporters: OpenLineage to a JSON-lines file and OpenTelemetry
       spans to an in-memory exporter.
   Each configuration's added cost is reported as a percentage over (a).
2. Throughput during an outage: rows/s for a clean run vs. a run in which a
   fallback-protected block crashes (its consumer reroutes to the fallback source) and
   vs. one in which an unprotected block crashes (its dependents read its stale
   last-good snapshot). Each timed run follows an untimed clean run in the same root.
3. Recovery time: wall time of `guardian shadow promote <block> --approve` (a separate
   process, as a human would run it) until it returns with the block HEALTHY, the
   candidate active and the quarantine replayed through it, with 1%, 10% and 50% of the
   block's rows quarantined.
4. Shadow cost: one pipeline run with one block's candidate version in shadow vs. none.

Blocks are chosen by DAG role (``blocks_by_role``), never by name. Methodology (warm-up,
repeats, fresh storage roots, statistics) is written into results.md.
"""

