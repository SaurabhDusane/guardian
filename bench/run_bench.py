def write_results(path: Path, meta: dict[str, Any], blocks: Blocks, series: list[Series]) -> dict:
    summaries = [s.summary() for s in series]
    results = {
        "schema": 1,
        "meta": meta,
        "blocks": blocks.as_dict(),
        "series": summaries,
        "derived": derive(summaries),
    }
    tmp = path.with_suffix(".json.tmp")
    tmp.write_text(json.dumps(results, indent=2) + "\n", encoding="utf-8")
    os.replace(tmp, path)
    return results


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--scales", type=int, nargs="+", help=f"rows (default {SCALES})")
    parser.add_argument("--repeats", type=int, help=f"measured repeats (default {REPEATS})")
    parser.add_argument("--quick", action="store_true", help="10k rows, 2 repeats")
    parser.add_argument(
        "--only", nargs="+", choices=MEASUREMENTS, default=list(MEASUREMENTS), metavar="NAME"
    )
    parser.add_argument(
        "--out-dir",
        type=Path,
        default=BENCH,
        help="where results.json and results.md go (--quick: results-quick.*)",
    )
    args = parser.parse_args(argv)
    scales = tuple(args.scales or (QUICK_SCALES if args.quick else SCALES))
    repeats = args.repeats or (QUICK_REPEATS if args.quick else REPEATS)
    if repeats < 1 or any(s < 100 for s in scales):
        parser.error("--repeats must be >= 1 and every scale >= 100 rows")
    stem = "results-quick" if args.quick else "results"
    args.out_dir.mkdir(parents=True, exist_ok=True)
    json_path, md_path = args.out_dir / f"{stem}.json", args.out_dir / f"{stem}.md"

    raw = raw_spec()
    blocks = pick_blocks(to_spec(raw))
    columns = derived_columns(to_spec(scaled(raw, 2_000, clean=True)), blocks.versioned)
    commit, dirty = git_commit(REPO)
    meta = {
        "command": " ".join(["python", "bench/run_bench.py", *sys.argv[1:]]),
        "quick": args.quick,
        "complete": False,
        "started": datetime.now(UTC).isoformat(timespec="seconds"),
        "finished": None,
        "scales": list(scales),
        "repeats": repeats,
        "warmups": 1,
        "sample_rate": SAMPLE_RATE,
        "quarantine_fractions": list(QUARANTINE_FRACTIONS),
        "measurements": args.only,
        "git_commit": commit,
        "git_dirty": dirty,
        "machine": machine(),
    }
    log(f"blocks by role: {blocks.as_dict()}")
    log(f"scales {list(scales)}, {repeats} repeats, writing {json_path}")

    series: list[Series] = []
    for scale in scales:
        for measurement in args.only:
            log(f"{measurement} at {scale:,} rows")
            if measurement == "overhead":
                series += bench_overhead(raw, scale, repeats)
            elif measurement == "throughput":
                series += bench_throughput(raw, scale, repeats, blocks)
            elif measurement == "recovery":
                series += bench_recovery(raw, scale, repeats, blocks, columns)
            else:
                series += bench_shadow(raw, scale, repeats, blocks)
            write_results(json_path, meta, blocks, series)  # partial results survive a crash

    meta.update(complete=True, finished=datetime.now(UTC).isoformat(timespec="seconds"))
    results = write_results(json_path, meta, blocks, series)
    sys.path.insert(0, str(BENCH))
    from update_readme import render_results_md

    md_path.write_text(render_results_md(results), encoding="utf-8")
    log(f"wrote {json_path} and {md_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
